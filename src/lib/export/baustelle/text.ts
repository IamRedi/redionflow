export function normalizeExportLang(lang?: string): ExportLang {
  return lang === "en" || lang === "it" || lang === "pl" || lang === "ro" || lang === "sq" ? lang : "de";
}

export function localeForExport(lang: ExportLang) {
  const locales: Record<ExportLang, string> = {
    de: "de-DE",
    en: "en",
    it: "it",
    pl: "pl",
    ro: "ro",
    sq: "sq",
  };
  return locales[lang];
}

