it('creates an independent crane firm, plans its own jobs and completes custody/repair without manufacturing',async()=>{
  vi.stubEnv('SESSION_SIGNING_SECRET','synthetic-crane-integration-signing-key-only');
  try{
    const raw=JSON.parse(readFileSync('examples/company-crane-muster.json','utf8')),plan=planCompanySetup(raw);
    await prisma.plan.upsert({where:{tier:'enterprise'},update:{},create:{tier:'enterprise',displayName:'Synthetic Enterprise'}});
    const foreign=await prisma.companyProfile.create({data:{id:foreignId,legalName:'Foreign synthetic sentinel',displayName:'Foreign synthetic sentinel'}});
    const foreignItem=await prisma.companyInventoryItem.create({data:{companyProfileId:foreignId,category:'WORK_TOOL',itemCode:'FOREIGN',name:'Foreign synthetic tool'}});
    const created=await applyCompanySetup(prisma,raw,plan.digest,hashPassword('Synthetic-crane-test-password'));
    expect(created.created).toBe(true);
    expect((await applyCompanySetup(prisma,raw,plan.digest,hashPassword('Different-synthetic-password'))).created).toBe(false);
    expect((await populateCraneMuster(prisma,672000)).created).toBe(true);
    expect((await populateCraneMuster(prisma,672000)).created).toBe(false);
    const owner=await prisma.user.findFirstOrThrow({where:{companyProfileId:CRANE_MUSTER_ID,isOwner:true}});
    const who=async(kind:'admin'|'worker',id:string)=>{request.values.clear();request.values.set(kind==='admin'?'bk_admin_id':'bk_worker_id',await createTestSession(kind,id));};
    await who('admin',owner.id);
    vi.stubEnv('VIRTUAL_OFFICE_WORK_ENABLED','true');
    vi.stubEnv('VIRTUAL_OFFICE_TEAM_ENABLED','true');
    vi.stubEnv('VIRTUAL_OFFICE_ACCESS_JSON',JSON.stringify({companyId:CRANE_MUSTER_ID,megi:{adminId:'unused-synthetic-seat'},almet:{adminId:owner.id}}));
    expect((await officeWorkSnapshot()).tasks.map(t=>t.title)).toEqual(['Musteraufträge und Freigaben prüfen']);
    await who('worker','crane-muster-finance');
    expect((await officeWorkSnapshot()).tasks.map(t=>t.title)).toEqual(['Einsatzstunden & Musterbelege prüfen']);
    expect((await officeWorkbooks(dateKey(new Date()).slice(0,7))).summary).toHaveLength(7);
    await who('worker','crane-muster-operator-a');
    await expect(officeWorkSnapshot()).rejects.toMatchObject({code:'DENIED'});
    await who('admin',owner.id);
    expect(await companyUiIdentity(CRANE_MUSTER_ID)).toBe('crane-red-blue-v1');expect(await companyUiIdentity(foreignId)).toBeNull();
    expect(await prisma.worker.count({where:{companyProfileId:CRANE_MUSTER_ID}})).toBe(7);
    expect(await prisma.baustelle.count({where:{companyProfileId:CRANE_MUSTER_ID,type:'STEEL_WORKSHOP'}})).toBe(0);
    expect((await createProductionBatchAction({baustelleId:(await prisma.baustelle.findFirstOrThrow({where:{companyProfileId:CRANE_MUSTER_ID}})).id,title:'Forbidden factory',unit:'t'})).ok).toBe(false);
    const dayPlans=await prisma.dailyWorkPlan.findMany({where:{companyProfileId:CRANE_MUSTER_ID},include:{savedRows:true,columns:{include:{assignments:{include:{machine:true}}}}}});
    expect(dayPlans).toHaveLength(2);
    for(const p of dayPlans){const assignments=p.columns.flatMap(c=>c.assignments);for(const key of ['workerId','machineId'] as const){const assigned=assignments.flatMap(a=>a[key]?[a[key]!]:[]);expect(new Set(assigned).size).toBe(assigned.length);}}
    for(const p of dayPlans)for(const c of p.columns){const m=c.assignments.find(a=>a.machine)?.machine;expect(p.savedRows.find(r=>r.baustelleName===c.title)?.machineNames).toBe(m?planMachineLabel(m):'');}
    const m=await prisma.machine.findFirstOrThrow({where:{companyProfileId:CRANE_MUSTER_ID,targe:'MU RK 101'}});
    expect(await prisma.companyAssetCode.count({where:{companyProfileId:CRANE_MUSTER_ID,asset:{machineId:m.id}}})).toBe(0);
    const item=await prisma.companyInventoryItem.findUniqueOrThrow({where:{companyProfileId_itemCode:{companyProfileId:CRANE_MUSTER_ID,itemCode:'RK-WZ-001'}}});
    const ref:AssetRef={kind:'inventory',id:item.id},machine:AssetRef={kind:'machine',id:m.id};
    expect((await readAssetSnapshot({scan:'RK-WZ-001'})).assets.map(a=>a.id)).toEqual([item.id]);
    const mutate=(command:AssetCommand)=>runAssetMutation({requestId:randomUUID(),command});
    const first=await mutate({type:'handover',asset:ref,kind:'issue',toWorkerId:'crane-muster-operator-a'}) as {handoverId:string};
    expect((await readAssetDetail(ref)).asset.holder).toBeNull();
    await who('worker','crane-muster-operator-a');
    await mutate({type:'confirm-handover',handoverId:first.handoverId,revision:1});
    expect((await readAssetDetail(ref)).asset.holder?.id).toBe('crane-muster-operator-a');
    const transfer=await mutate({type:'handover',asset:ref,kind:'transfer',toWorkerId:'crane-muster-operator-b'}) as {handoverId:string};
    // The sender's explicit request is their signature; it cannot sign for the recipient.
    expect((await readAssetDetail(ref)).handovers.find(h=>h.id===transfer.handoverId)?.confirmations.map(c=>c.confirmed)).toEqual([true,false]);
    expect((await readAssetDetail(ref)).asset.holder?.id).toBe('crane-muster-operator-a');
    await who('worker','crane-muster-operator-b');
    await mutate({type:'confirm-handover',handoverId:transfer.handoverId,revision:1});
    expect((await readAssetDetail(ref)).asset.holder?.id).toBe('crane-muster-operator-b');
    await expect(readAssetDetail({kind:'inventory',id:foreignItem.id})).rejects.toMatchObject({code:'NOT_FOUND'});
    const returned=await mutate({type:'handover',asset:ref,kind:'return'}) as {handoverId:string};
    await who('admin',owner.id);await mutate({type:'confirm-handover',handoverId:returned.handoverId,revision:1});
    expect((await readAssetDetail(ref)).asset.holder).toBeNull();
    const report=await mutate({type:'report',asset:machine,kind:'defect',note:'MUSTER · Hydraulikleitung kontrollieren'}) as {repairId:string};
    const boss=await assetActor();
    await expect(withTenantContext(CRANE_MUSTER_ID,tx=>assertAssetUsable(tx,boss,machine))).rejects.toMatchObject({code:'ASSET_UNAVAILABLE'});
    await who('worker','crane-muster-mechanic');
    await mutate({type:'repair-phase',repairId:report.repairId,revision:1,phase:'received'});
    await mutate({type:'repair-phase',repairId:report.repairId,revision:2,phase:'repairing'});
    await expect(mutate({type:'repair-phase',repairId:report.repairId,revision:3,phase:'ready'})).rejects.toMatchObject({code:'REPAIR_EVIDENCE_REQUIRED'});
    const form=new FormData();form.set('assetKind','machine');form.set('assetId',m.id);form.set('kind','document');form.set('repairId',report.repairId);form.set('requestId',randomUUID());
    form.set('file',new File(['%PDF-1.4\nSynthetic crane repair evidence\n%%EOF'],'Werkstatt-MUSTER.pdf',{type:'application/pdf'}));
    const file=await saveCompanyAssetFile(form);
    await mutate({type:'repair-phase',repairId:report.repairId,revision:3,phase:'ready',tested:true,repairNote:'MUSTER · Leitung ersetzt und Funktionsprüfung dokumentiert.'});
    expect((await readCompanyAssetFile(file.id)).mime).toBe('application/pdf');
    await who('admin',owner.id);
    await expect(withTenantContext(CRANE_MUSTER_ID,tx=>assertAssetUsable(tx,boss,machine))).resolves.toBeDefined();
    const element=await prisma.siteElement.findFirstOrThrow({where:{companyProfileId:CRANE_MUSTER_ID}});
    expect(element.factoryDoneAt).toBeNull();
    expect((await addElementWorkAction({elementId:element.id,stage:'received',pieces:1,workerIds:['crane-muster-operator-a']})).ok).toBe(true);
    expect((await addElementWorkAction({elementId:element.id,stage:'cutting',pieces:1,workerIds:['crane-muster-operator-a']})).ok).toBe(false);
    expect(await prisma.productionEvent.count({where:{companyProfileId:CRANE_MUSTER_ID}})).toBe(0);
    expect((await readAssetDetail(machine)).history.filter(e=>e.type.startsWith('repair.')).map(e=>e.type)).toEqual(expect.arrayContaining(['repair.received','repair.repairing','repair.ready']));
    expect(await prisma.companyProfile.findUnique({where:{id:foreignId}})).toEqual(foreign);
  }finally{vi.unstubAllEnvs();}
},60_000);
