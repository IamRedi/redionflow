import { expect, test } from "@playwright/test";
import { workshopCopy } from "../../src/lib/workshop/copy";
import { resetWorkshopFixture } from "./shared-fixture";

test("one navigation, expandable search, readable ice filter and three registration methods preserve inventory", async ({ page, context, request }, info) => {
  await resetWorkshopFixture();
  const base = String(info.project.use.baseURL);
  await context.addCookies([{ name: "bk_lang", value: "de", url: base }]);
  const before = await (await request.get("/api/demo/baumdienst/workshop")).json();
  await page.addInitScript(() => {
    const signals: AbortSignal[] = [];
    Object.assign(window, { registrationNfcSignals: signals, NDEFReader: class { onreading = null; onreadingerror = null; async scan({ signal }: { signal: AbortSignal }) { signals.push(signal); } } });
  });
  const search = "Name, Kennzeichen, Code oder Defekt suchen…";
  const labels = ["Workzone", "Kontrollpanel", "Büros", "Dashboard view", "Holzwerkstatt", "Werkstatt", "Inventar", "Flotte"];
  for (const theme of ["light", "dark"]) for (const width of [1440, 390]) {
    await context.addCookies([{ name: "bk_theme", value: theme, url: base }]);
    await page.setViewportSize({ width, height: 900 });
    await page.goto("/demo/workshop?tab=tools");
    const nav = page.getByRole("navigation", { name: "Demo", exact: true });
    for (const label of labels) await expect(nav.getByRole("link", { name: label, exact: true })).toHaveCount(1);
    await expect(page.getByRole("link", { name: "Inventar", exact: true })).toHaveCount(1);
    await expect(nav.getByRole("link", { name: "Inventar", exact: true })).toBeInViewport();
    await expect(page.getByRole("link", { name: "Werkstatt", exact: true })).toHaveCount(1);
    await expect(page.getByRole("button", { name: workshopCopy("de").refresh, exact: true })).toHaveCount(0);
    await expect(page.getByRole("button", { name: "Scannen", exact: true })).toHaveCount(0);
    await expect(page.getByRole("searchbox", { name: search, exact: true })).toHaveCount(0);
    const trigger = page.getByRole("button", { name: search, exact: true });
    await trigger.click();
    const input = page.getByRole("searchbox", { name: search, exact: true });
    await expect(input).toBeFocused(); await input.fill("no-match-74195");
    await expect(page.getByTestId("workshop-scroll-region").locator("article")).toHaveCount(0);
    await input.press("Escape"); await expect(trigger).toBeFocused();
    await expect(page.getByRole("searchbox", { name: search, exact: true })).toHaveCount(0);
    await expect(page.getByTestId("workshop-scroll-region").locator("article").first()).toBeVisible();
    await page.getByRole("combobox", { name: "Alle Geräte", exact: true }).click();
    const menu = page.getByRole("listbox");
    await expect(menu).toBeVisible();
    expect(await menu.evaluate(e => getComputedStyle(e).backgroundImage)).toContain("linear-gradient");
    expect(await menu.evaluate(e => getComputedStyle(e).color)).not.toBe(theme === "dark" ? "rgb(0, 0, 0)" : "rgb(255, 255, 255)");
    await page.screenshot({ path: info.outputPath(`filter-${theme}-${width}.png`) });
    await page.getByRole("option", { name: "Werkzeuge", exact: true }).click();
    await expect(page.getByTestId("fleet-asset-card")).toHaveCount(0);
    await page.getByRole("combobox", { name: "Alle Geräte", exact: true }).click();
    await page.getByRole("option", { name: "Alle Geräte", exact: true }).click();
    await page.getByRole("button", { name: "Gerät erfassen", exact: true }).click();
    const dialog = page.getByRole("dialog");
    for (const name of ["Name / neuer Barcode", "Kamera", "NFC"]) await expect(dialog.getByRole("button", { name, exact: true })).toBeVisible();
    await dialog.getByRole("button", { name: "Name / neuer Barcode", exact: true }).click();
    await expect(dialog.getByLabel("Bezeichnung", { exact: true })).toBeVisible();
    await page.keyboard.press("Escape");
    await expect(page.getByRole("button", { name: "Gerät erfassen", exact: true })).toBeFocused();
    await page.getByRole("button", { name: "Gerät erfassen", exact: true }).click();
    await dialog.getByRole("button", { name: "NFC", exact: true }).click();
    await expect.poll(() => page.evaluate(() => (window as unknown as { registrationNfcSignals: AbortSignal[] }).registrationNfcSignals.length)).toBe(1);
    await page.keyboard.press("Escape");
    expect(await page.evaluate(() => (window as unknown as { registrationNfcSignals: AbortSignal[] }).registrationNfcSignals.every(s => s.aborted))).toBe(true);
    await page.getByRole("navigation", {name:"Demo",exact:true}).getByRole("link",{name:"Flotte",exact:true}).click();
    await page.getByTestId("fleet-asset-card").filter({has:page.getByRole("heading",{name:"Kran-LKW",exact:true})}).getByRole("button",{name:"Details öffnen",exact:true}).click();
    await page.getByRole("dialog").getByText("Service & Details",{exact:true}).click();
    const quick = page.getByRole("dialog");
    await expect(quick).toBeVisible();
    const bounds = (await quick.boundingBox())!; expect(bounds.y).toBeGreaterThanOrEqual(0); expect(bounds.y + bounds.height).toBeLessThanOrEqual(901);
    const manage = quick.getByRole("link",{name:"Fahrzeugakte",exact:true}); await expect(manage).toHaveAttribute("href", /^\/demo\/machines\//); await manage.scrollIntoViewIfNeeded(); await expect(manage).toBeInViewport();
    await quick.getByRole("button", { name: "Schließen", exact: true }).click();
    const list = page.getByTestId("workshop-scroll-region");
    await list.focus(); await page.keyboard.press("Control+End");
    const row = page.getByTestId("baumdienst-demo-footer"); await expect(row).toBeInViewport();
    const boxes = await row.locator('nav,footer,[data-testid="baumdienst-product-mark"]').evaluateAll(es => es.map(e => e.getBoundingClientRect().toJSON()));
    if (width >= 390) expect(Math.max(...boxes.map(b => b.y)) - Math.min(...boxes.map(b => b.y))).toBeLessThan(2);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight + 1)).toBe(true);
  }
  const site = before.directory.sites[0];
  await page.goto(`/demo/workshop?tab=tools&site=${site.key}`);
  await expect(page.getByRole("navigation", { name: "Demo", exact: true }).getByRole("link", { name: "Flotte", exact: true })).toHaveAttribute("href", `/demo/workshop?tab=fleet&site=${site.key}`);
  const after = await (await request.get("/api/demo/baumdienst/workshop")).json();
  expect(after.revision).toBe(before.revision); expect(after.state).toEqual(before.state);
});
